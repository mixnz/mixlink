//! Client keys (spec 0021): set-1 scan code (as a low-level keyboard hook reports it) → HID usage on
//! page 0x07. Layout-free: the host's keyboard layout decides the character. Only usages the `vhid`
//! keyboard report carries are returned (see `hid::keyboard`).

/// `VK_PAUSE`: its scan code (0x45, often without the extended flag) is shared with NumLock.
const VK_PAUSE: u16 = 0x13;
const VK_NUMLOCK: u16 = 0x90;
/// AltGr's fake left Ctrl comes with this bit set on its scan code.
const FAKE_SCAN: u16 = 0x200;

/// HID usage of a key, or `None` for keys the report has no bit for (media keys, odd scan codes).
// HOT PATH
pub fn usage(scan: u16, extended: bool, vk: u16) -> Option<u8> {
    match vk {
        VK_PAUSE => return Some(0x48),
        VK_NUMLOCK => return Some(0x53),
        _ => {}
    }
    if scan & FAKE_SCAN != 0 || scan > 0x7F {
        return None;
    }
    let code = scan as u8;
    let found = if extended {
        extended_usage(code)
    } else {
        BASE[usize::from(code)]
    };
    (found != 0).then_some(found)
}

/// Keys behind the 0xE0 prefix.
const fn extended_usage(scan: u8) -> u8 {
    match scan {
        0x1C => 0x58, // keypad Enter
        0x1D => 0xE4, // right Ctrl
        0x35 => 0x54, // keypad /
        0x37 => 0x46, // Print Screen
        0x38 => 0xE6, // right Alt
        0x46 => 0x48, // Ctrl+Break = Pause
        0x47 => 0x4A, // Home
        0x48 => 0x52, // Up
        0x49 => 0x4B, // Page Up
        0x4B => 0x50, // Left
        0x4D => 0x4F, // Right
        0x4F => 0x4D, // End
        0x50 => 0x51, // Down
        0x51 => 0x4E, // Page Down
        0x52 => 0x49, // Insert
        0x53 => 0x4C, // Delete
        0x5B => 0xE3, // left Windows
        0x5C => 0xE7, // right Windows
        0x5D => 0x65, // Application (menu)
        _ => 0,
    }
}

